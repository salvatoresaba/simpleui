// Command gensurface snapshots the exported API surface of a Go package.
//
// It is the tool that produced the pre-refactor golden file of the `sui`
// package and the compile-time method assertions that pin the facade.
//
// Usage:
//
//	go run ./internal/apitools/cmd/gensurface -dir . -pkg github.com/salvatoresaba/simpleui \
//	    -out internal/apitools/testdata/api_surface.txt \
//	    -methods-out internal/apitools/api_methods_test.go
package main

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/salvatoresaba/simpleui/internal/apitools"
)

func main() {
	dir := flag.String("dir", ".", "directory holding the package sources")
	pkg := flag.String("pkg", "", "import path of the package (required with -methods-out)")
	out := flag.String("out", "", "path of the golden snapshot to write")
	methodsOut := flag.String("methods-out", "", "path of the generated method assertions to write")
	flag.Parse()

	surface, err := apitools.ExtractDir(*dir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gensurface: %v\n", err)
		os.Exit(1)
	}

	if *out != "" {
		if err := apitools.WriteGolden(*out, surface); err != nil {
			fmt.Fprintf(os.Stderr, "gensurface: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("wrote %s (%d functions, %d types, %d constants, %d variables, %d methods)\n",
			*out, len(surface.Funcs), len(surface.Types), len(surface.Consts), len(surface.Vars), len(surface.Methods))
	}

	if *methodsOut != "" {
		if *pkg == "" {
			fmt.Fprintln(os.Stderr, "gensurface: -pkg is required with -methods-out")
			os.Exit(1)
		}
		if err := writeMethodAssertions(*methodsOut, *pkg, surface); err != nil {
			fmt.Fprintf(os.Stderr, "gensurface: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("wrote %s (%d method assertions)\n", *methodsOut, len(surface.Methods))
	}
}

func writeMethodAssertions(path, pkg string, surface *apitools.Surface) error {
	seen := map[string]bool{}
	var lines []string
	for _, m := range surface.Methods {
		if m.Receiver == "" {
			continue
		}
		key := m.Receiver + "." + m.Name
		if seen[key] {
			continue
		}
		seen[key] = true
		lines = append(lines, fmt.Sprintf("\t_ = %s", m.Expression("sui")))
	}
	sort.Strings(lines)

	var b strings.Builder
	b.WriteString("// Code generated by internal/apitools/cmd/gensurface. DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// Compile-time proof that every method of the public API surface is\n")
	b.WriteString("// still reachable through the package facade. A missing method breaks the\n")
	b.WriteString("// build; a changed signature is caught by the alias identity.\n")
	b.WriteString("\npackage apitools\n\n")
	b.WriteString("import sui \"" + pkg + "\"\n\n")
	b.WriteString("var (\n")
	for _, line := range lines {
		b.WriteString(line + "\n")
	}
	b.WriteString(")\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}
