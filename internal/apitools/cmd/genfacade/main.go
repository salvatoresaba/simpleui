// Command genfacade generates the public facade of the SimpleUI package.
//
// The compiler implementation lives in internal/core. The root package keeps
// the public API of github.com/salvatoresaba/simpleui alive through type
// aliases and thin wrappers, so importers do not have to change.
//
// Usage:
//
//	go run ./internal/apitools/cmd/genfacade -dir internal/core -out facade.go
package main

import (
	"flag"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"

	"github.com/salvatoresaba/simpleui/internal/apitools"
)

// coreImport is the import path of the package holding the implementation.
const coreImport = "github.com/salvatoresaba/simpleui/internal/core"

// qualifierRe finds package qualifiers inside a rendered signature.
var qualifierRe = regexp.MustCompile(`\b([a-z][A-Za-z0-9_]*)\.`)

// qualifierImports maps a qualifier to the package it refers to.
var qualifierImports = map[string]string{
	"net":      "net",
	"http":     "net/http",
	"httptest": "net/http/httptest",
	"testing":  "testing",
}

func main() {
	dir := flag.String("dir", "internal/core", "directory holding the implementation package")
	out := flag.String("out", "facade.go", "path of the generated facade")
	exclude := flag.String("exclude", "", "comma separated names that must not be re-exported")
	flag.Parse()

	skip := map[string]bool{}
	for _, name := range strings.Split(*exclude, ",") {
		name = strings.TrimSpace(name)
		if name != "" {
			skip[name] = true
		}
	}

	surface, err := apitools.ExtractDir(*dir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "genfacade: %v\n", err)
		os.Exit(1)
	}
	filtered := &apitools.Surface{}
	for _, f := range surface.Funcs {
		if !skip[f.Name] {
			filtered.Funcs = append(filtered.Funcs, f)
		}
	}
	for _, t := range surface.Types {
		if !skip[t.Name] {
			filtered.Types = append(filtered.Types, t)
		}
	}
	for _, c := range surface.Consts {
		if !skip[c.Name] {
			filtered.Consts = append(filtered.Consts, c)
		}
	}
	for _, v := range surface.Vars {
		if !skip[v.Name] {
			filtered.Vars = append(filtered.Vars, v)
		}
	}
	code, err := render(filtered)
	if err != nil {
		fmt.Fprintf(os.Stderr, "genfacade: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, []byte(code), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "genfacade: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s (%d functions, %d types, %d constants, %d variables)\n",
		*out, len(filtered.Funcs), len(filtered.Types), len(filtered.Consts), len(filtered.Vars))
}

func render(surface *apitools.Surface) (string, error) {
	imports, err := collectImports(surface)
	if err != nil {
		return "", err
	}

	var b strings.Builder
	b.WriteString("// Code generated by internal/apitools/cmd/genfacade. DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// Package sui is the public facade of the SimpleUI compiler.\n")
	b.WriteString("//\n")
	b.WriteString("// The implementation lives in internal/core; this package re-exports it\n")
	b.WriteString("// so that github.com/salvatoresaba/simpleui keeps the same API it always\n")
	b.WriteString("// had. Types are aliases, so identity, methods and conversions are\n")
	b.WriteString("// preserved exactly; functions are thin wrappers.\n")
	b.WriteString("package sui\n\n")
	b.WriteString("import (\n")
	for _, imp := range imports {
		b.WriteString("\t\"" + imp + "\"\n")
	}
	b.WriteString(")\n\n")

	b.WriteString("// ---------------------------------------------------------------------------\n")
	b.WriteString("// Types\n")
	b.WriteString("// ---------------------------------------------------------------------------\n\n")
	for _, t := range surface.Types {
		writeDoc(&b, t.Doc)
		b.WriteString("type " + t.Name + " = core." + t.Name + "\n\n")
	}

	b.WriteString("// ---------------------------------------------------------------------------\n")
	b.WriteString("// Constants\n")
	b.WriteString("// ---------------------------------------------------------------------------\n\n")
	for _, c := range surface.Consts {
		writeDoc(&b, c.Doc)
		b.WriteString("const " + c.Name + " = core." + c.Name + "\n\n")
	}

	b.WriteString("// ---------------------------------------------------------------------------\n")
	b.WriteString("// Variables\n")
	b.WriteString("// ---------------------------------------------------------------------------\n\n")
	for _, v := range surface.Vars {
		writeDoc(&b, v.Doc)
		b.WriteString("var " + v.Name + " = core." + v.Name + "\n\n")
	}

	b.WriteString("// ---------------------------------------------------------------------------\n")
	b.WriteString("// Functions\n")
	b.WriteString("// ---------------------------------------------------------------------------\n\n")
	for _, f := range surface.Funcs {
		writeDoc(&b, f.Doc)
		b.WriteString(f.Signature() + " {\n")
		call := "core." + f.Name + "(" + f.Call() + ")"
		if len(f.Results) == 0 {
			b.WriteString("\t" + call + "\n")
		} else {
			b.WriteString("\treturn " + call + "\n")
		}
		b.WriteString("}\n\n")
	}
	return b.String(), nil
}

// collectImports returns the sorted import list required by the facade: the
// implementation package plus every package qualifier used by a signature.
func collectImports(surface *apitools.Surface) ([]string, error) {
	seen := map[string]bool{}
	for _, f := range surface.Funcs {
		for _, match := range qualifierRe.FindAllStringSubmatch(f.Signature(), -1) {
			qualifier := match[1]
			imp, ok := qualifierImports[qualifier]
			if !ok {
				return nil, fmt.Errorf("unknown package qualifier %q in signature %q: add it to qualifierImports", qualifier, f.Signature())
			}
			seen[imp] = true
		}
	}
	seen[coreImport] = true
	imports := make([]string, 0, len(seen))
	for imp := range seen {
		imports = append(imports, imp)
	}
	sort.Strings(imports)
	return imports, nil
}

// writeDoc copies a doc comment, if any, above the generated declaration.
func writeDoc(b *strings.Builder, doc string) {
	if doc == "" {
		return
	}
	for _, line := range strings.Split(doc, "\n") {
		b.WriteString("// " + line + "\n")
	}
}
